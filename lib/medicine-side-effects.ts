const FLUID = /^(dextrose|sodium chloride|ringer|glucose 50)/;
const compiled = SIDE_EFFECTS.map(([p, effects]) => ({ re: new RegExp(p, "i"), fluid: FLUID.test(p), list: effects.split(", ") }));

/** Up to five common side effects for a regimen name; combinations show two per component. Null when unknown. */
export function sideEffectsFor(genericName: string): string[] | null {
  let hits = compiled.flatMap((entry) => { const m = entry.re.exec(genericName); return m ? [{ entry, text: m[0].toLowerCase() }] : []; });
  if (!hits.length) return null;
  if (hits.some((h) => !h.entry.fluid)) hits = hits.filter((h) => !h.entry.fluid);
  hits = hits.filter((h) => !hits.some((o) => o !== h && o.text !== h.text && o.text.includes(h.text)));
  const unique = hits.filter((h, i) => hits.findIndex((o) => o.entry === h.entry) === i);
  if (unique.length === 1) return unique[0].entry.list.slice(0, 5);
  return unique.slice(0, 3).map((h) => `${h.text.replace(/^./, (c) => c.toUpperCase())}: ${h.entry.list.slice(0, 2).join(", ")}`);
}
